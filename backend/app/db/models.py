"""Persistence models.

Deliberately narrow. The operational world (flights, crew, rosters, duty
clocks) is a read-only snapshot loaded from JSON into ``app.core.World`` -- it
is never written, so mirroring it into tables would add a second source of
truth for no gain. What the database holds is everything the system *produces*:

  * agent runs, spans, facts and rule evaluations  -- the audit trail
  * conversations and messages                      -- multi-turn context
  * decisions and notifications                     -- what a controller did
  * alerts                                          -- what the watchers found
  * eval runs                                       -- correctness over time

The world tables are still generated (see ``etl.py``) for teams that want to
query the schedule with SQL, but nothing in the answer path depends on them.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship
from sqlalchemy.types import JSON


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Base(DeclarativeBase):
    type_annotation_map = {dict[str, Any]: JSON, list: JSON}


# ==========================================================================
# World snapshot (generated by ETL; read path does not depend on these)
# ==========================================================================


class Station(Base):
    __tablename__ = "stations"
    code: Mapped[str] = mapped_column(String(3), primary_key=True)


class Aircraft(Base):
    __tablename__ = "aircraft"
    tail: Mapped[str] = mapped_column(String(16), primary_key=True)
    aircraft_type: Mapped[str] = mapped_column(String(16))
    seats: Mapped[int] = mapped_column(Integer)


class Flight(Base):
    __tablename__ = "flights"
    flight_id: Mapped[str] = mapped_column(String(32), primary_key=True)
    flight_no: Mapped[str] = mapped_column(String(8), index=True)
    date: Mapped[Any] = mapped_column(Date, index=True)
    dep_station: Mapped[str] = mapped_column(String(3), index=True)
    arr_station: Mapped[str] = mapped_column(String(3), index=True)
    dep_utc: Mapped[datetime] = mapped_column(DateTime)
    arr_utc: Mapped[datetime] = mapped_column(DateTime)
    block_hours: Mapped[float] = mapped_column(Float)
    aircraft: Mapped[str] = mapped_column(String(16), index=True)
    aircraft_type: Mapped[str] = mapped_column(String(16))
    seats: Mapped[int] = mapped_column(Integer)

    __table_args__ = (Index("ix_flights_date_dep", "date", "dep_station"),)


class Crew(Base):
    __tablename__ = "crew"
    crew_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    name: Mapped[str] = mapped_column(String(64))
    rank: Mapped[str] = mapped_column(String(32), index=True)
    base: Mapped[str] = mapped_column(String(3), index=True)
    seniority: Mapped[int] = mapped_column(Integer)
    reachability_minutes: Mapped[int] = mapped_column(Integer)
    status: Mapped[str] = mapped_column(String(16), index=True)


class CrewRating(Base):
    __tablename__ = "crew_ratings"
    crew_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    aircraft_type: Mapped[str] = mapped_column(String(16), primary_key=True)


class Pairing(Base):
    __tablename__ = "pairings"
    pairing_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    aircraft: Mapped[str] = mapped_column(String(16), index=True)


class PairingDay(Base):
    __tablename__ = "pairing_days"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    pairing_id: Mapped[str] = mapped_column(String(16), index=True)
    day_index: Mapped[int] = mapped_column(Integer)
    date: Mapped[Any] = mapped_column(Date, index=True)
    report_utc: Mapped[datetime] = mapped_column(DateTime)
    release_utc: Mapped[datetime] = mapped_column(DateTime)
    sectors: Mapped[int] = mapped_column(Integer)
    duty_hours: Mapped[float] = mapped_column(Float)
    flight_hours: Mapped[float] = mapped_column(Float)
    flight_ids: Mapped[list] = mapped_column(JSON)


class PairingCrew(Base):
    __tablename__ = "pairing_crew"
    pairing_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    crew_id: Mapped[str] = mapped_column(String(16), primary_key=True, index=True)
    role: Mapped[str] = mapped_column(String(32))


class DutyClockDaily(Base):
    __tablename__ = "duty_clock_daily"
    crew_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    date: Mapped[Any] = mapped_column(Date, primary_key=True)
    duty_hours: Mapped[float] = mapped_column(Float)
    flight_hours: Mapped[float] = mapped_column(Float)


class DutyClockSummary(Base):
    __tablename__ = "duty_clock_summary"
    crew_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    as_of_utc: Mapped[datetime] = mapped_column(DateTime)
    duty_hours_7d: Mapped[float] = mapped_column(Float)
    flight_hours_28d: Mapped[float] = mapped_column(Float)
    last_rest_ended: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)


class ReserveAssignment(Base):
    __tablename__ = "reserve_assignments"
    crew_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    date: Mapped[Any] = mapped_column(Date, primary_key=True)
    base: Mapped[str] = mapped_column(String(3), index=True)
    oncall_start: Mapped[str] = mapped_column(String(5))
    oncall_end: Mapped[str] = mapped_column(String(5))


class Certification(Base):
    __tablename__ = "certifications"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    crew_id: Mapped[str] = mapped_column(String(16), index=True)
    cert_type: Mapped[str] = mapped_column(String(32))
    valid_from: Mapped[Any] = mapped_column(Date)
    valid_to: Mapped[Any] = mapped_column(Date, index=True)


class RuleRow(Base):
    __tablename__ = "rules"
    rule_id: Mapped[str] = mapped_column(String(32), primary_key=True)
    text: Mapped[str] = mapped_column(Text)
    params: Mapped[dict[str, Any]] = mapped_column(JSON, default=dict)


class CostRate(Base):
    __tablename__ = "cost_rates"
    key: Mapped[str] = mapped_column(String(48), primary_key=True)
    value: Mapped[int] = mapped_column(Integer)
    currency: Mapped[str] = mapped_column(String(8))


class RiskSignalRow(Base):
    __tablename__ = "risk_signals"
    crew_id: Mapped[str] = mapped_column(String(16), primary_key=True)
    as_of_utc: Mapped[datetime] = mapped_column(DateTime)
    score: Mapped[float] = mapped_column(Float, index=True)
    drivers: Mapped[list] = mapped_column(JSON)


# ==========================================================================
# Conversations
# ==========================================================================


class Conversation(Base):
    __tablename__ = "conversations"
    id: Mapped[str] = mapped_column(String(40), primary_key=True)
    title: Mapped[str] = mapped_column(String(200), default="")
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow, onupdate=utcnow)

    messages: Mapped[list["Message"]] = relationship(
        back_populates="conversation", cascade="all, delete-orphan", order_by="Message.created_at"
    )


class Message(Base):
    __tablename__ = "messages"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    conversation_id: Mapped[str] = mapped_column(
        ForeignKey("conversations.id", ondelete="CASCADE"), index=True
    )
    role: Mapped[str] = mapped_column(String(16))
    content: Mapped[str] = mapped_column(Text)
    answer_json: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)
    run_id: Mapped[str | None] = mapped_column(String(40), nullable=True, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)

    conversation: Mapped[Conversation] = relationship(back_populates="messages")


